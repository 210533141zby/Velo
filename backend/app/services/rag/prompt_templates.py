from __future__ import annotations

def build_no_context_answer() -> str:
    """返回系统统一使用的拒答文案。

    所有无证据回答都尽量复用同一表述，便于前端展示、实验统计和拒答检测
    保持同一口径。
    """
    return '根据当前检索到的知识库内容，没有找到足够相关的参考资料，因此我暂时无法给出可靠回答。'


def build_simple_rag_prompt(query: str, context: str) -> str:
    """构建最轻量的直接作答提示词。

    这套模板主要服务基线回答路径，只要求模型依据给定资料正面回答，
    不引入额外中间结构。
    """
    no_context = build_no_context_answer()
    return (
        f"你是一个问答助手。请仅根据下列资料直接回答用户问题。\n"
        f"- 第一句必须正面回答问题，不要写背景、评价或来源说明。\n"
        f"- 如果资料不足以得到可靠答案，原样回答：{no_context}\n"
        f"- 保持简洁，不要重复标题或编号，不要输出 JSON 或代码块。\n\n"
        f"资料：\n{context}\n\n"
        f"用户问题：{query}\n"
        f"回答："
    )


def build_document_judge_prompt(query: str, title: str, content: str) -> str:
    """构建单文档证据判别提示词。

    模型需要在这一步完成“主题是否对齐”“是否有直接证据”“能否直接回答”
    三层判断，并把结果压成稳定 JSON 供评分器消费。
    """
    return f"""
    你是 RAG 证据审核器。请先在心里完成主题判断、证据判断与可回答性判断，再只输出 JSON，不要输出任何解释、标题、代码块或额外文本。

    JSON 结构如下：
    {{
      "core_topic_match": "yes/no",
      "contains_direct_evidence": "yes/no",
      "answerable": "yes/no",
      "evidence_quote": "若能回答，摘录最关键原文；否则留空",
      "answer_brief": "若能回答，用一句简体中文直接回答；否则留空",
      "reason": "不超过18字"
    }}

    判定规则：
    1. core_topic_match 判断文档核心是否围绕用户真正询问的主体、属性、关系或事件，而不是只顺带提到相关词。
    2. contains_direct_evidence 判断文档里是否存在可直接支撑答案的原文证据，而不是只有模糊背景、弱关联或推测。
    3. answerable 只有在前两项都满足时才可以是 yes。
    4. 如果问题带有限定修饰、所属关系或多实体约束，必须确认这些约束在文档里被明确满足，不能把主体错配或属性错配的句子当答案。
    5. 如果问题要求关系、比较、共同点或并列事实，只有在文档明确给出对应联系或可复述事实时，才能判 contains_direct_evidence=yes。
    6. 如果问题只是一个短实体名，只要文档对这个对象给出了可直接复述的身份、行为或属性信息，就可以判 core_topic_match=yes；仅仅列表式顺带提及才算不匹配。
    7. evidence_quote 必须来自文档原文，不能编造，不超过 80 个字。
    8. answer_brief 只能根据 evidence_quote 组织答案，不能补充文档里没有的事实。

    用户问题：
    {query}

    文档标题：
    {title}

    文档内容：
    {content}
    """


def build_answer_synthesis_prompt(
    query: str,
    context: str,
    *,
    question_focus: str,
    response_format: str,
    focus_terms: str = '',
) -> str:
    """构建主综合器使用的证据约束提示词。

    该模板强调只能依据证据单元回答，并要求模型同时处理覆盖、冲突和
    引用单元选择，服务后端生成式综合路径。
    """
    return f"""
    你是 RAG 的答案综合器。你的任务是只基于给定证据单元完成回答，不要依赖外部常识，不要补充证据外事实。
    请先在心里完成证据筛选、答案组织和最终作答，然后只输出 JSON。

    JSON 结构如下：
    {{
      "verdict": "answer/no_context",
      "answer": "最终回答；证据不足时留空",
      "cited_unit_ids": ["至少1个被使用的 unit_id"]
    }}

    严格规则：
    1. 只能依据证据单元回答，不能编造或补充证据外事实。
    2. 你必须先根据证据自行判断答案应是单事实、并列列举、综合说明还是摘要，不依赖任何外部提示。
    3. 回答第一句必须直接回答用户问题，不要先写背景、评价、来源说明或系统说明。
    4. 如果问题需要综合多个事实点，答案必须完整覆盖这些被证据支持的关键信息；如果只是单一事实，则保持简洁。
    5. 如果不同证据单元存在冲突，只能保留被更直接、更一致证据支持的结论；必要时在答案中显式说明不确定性。
    6. 如果证据不足以可靠回答，verdict 必须为 no_context，answer 留空。
    7. cited_unit_ids 只能填写当前证据上下文中真实存在的 unit_id。
    8. 对强断言必须保留证据原有强度，不得把弱相关或推测改写成确定事实。
    9. 优先复用证据中的关键表述，只做最小必要改写，避免空泛总结。
    10. 证据单元中的“回答相关度”表示它直接回应问题的可能性；优先使用高回答相关度且内容具体的证据。
    11. 用户的核心疑问是：{question_focus}。你的回答第一句必须直接、明确地回应这个疑问，不能只给背景或相关事实。
    12. 需要重点对齐的语义槽位：{focus_terms or '无显式槽位，直接对齐核心事实'}。
    13. 回答组织要求：{response_format}

    用户问题：
    {query}

    证据单元：
    {context}
    """


def build_deep_review_prompt(query: str, context: str) -> str:
    """构建深度复核阶段的一体化提示词。

    与普通综合不同，这个模板会让模型在一次调用里同时做噪声过滤、
    冲突消解、回答规划和最终作答，更适合重型复核路线。
    """
    return f"""
    你是 RAG 的深层证据审查员。你的任务是只基于给定证据单元，一次性完成噪声过滤、证据评级、冲突检测、回答规划与答案生成。
    请先在心里完成分析，再只输出 JSON，不要输出解释、标题、代码块或额外文本。

    JSON 结构如下：
    {{
      "verdict": "answer/no_context",
      "answer": "最终给用户的回答。若证据不足则留空",
      "used_ranks": [1, 2]
    }}

    严格规则：
    1. 只能依据证据单元回答，不能补充证据外事实。
    2. 你必须先在内部完成噪声过滤、冲突消解与答案组织，但不要把中间分析写出来。
    3. 如果证据只是顺带提及、主体错配、属性错配或明显噪声，不能把它当作答案依据。
    4. 如果不同证据之间存在时间、数字、身份或结论冲突，answer 只能保留被更直接、更一致证据支持的结论；必要时显式说明不确定性。
    5. 如果证据不足以可靠回答，verdict 必须为 no_context，answer 留空。
    6. answer 的第一句必须直接回答用户问题；若是列表或综合问题，要完整但克制，不要写空泛背景。
    7. 如果证据单元里已经出现可直接复述的显式事实、数值、时间、命名或并列要点，应优先基于这些直接证据作答，而不是轻易输出 no_context。
    8. 即使当前证据集合中混有噪声，只要存在可靠证据，也应保留这些证据并完成回答，而不是被噪声带偏到拒答。
    9. 如果证据里已经有能直接回答问题的原句，answer 应尽量复用该句，只做最小必要改写，不要改写成更泛化、更空泛的表达。
    10. 对单事实问题，answer 尽量控制为一句；对需要解释或综合的问题，answer 应保留证据中明确存在的关键逻辑链，而不是压缩成标签。
    11. used_ranks 填写的是你实际依赖的来源排序编号，也就是证据单元中的“来源排序”字段，不是证据单元序号。

    用户问题：
    {query}

    证据单元：
    {context}
    """
